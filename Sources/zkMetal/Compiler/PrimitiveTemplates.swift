/// Auto-register all templates
extension PrimitiveRegistry {
    static func registerAllTemplates() {
        PrimitiveRegistry.register(Poseidon2Template.self)
        PrimitiveRegistry.register(MerkleTreeTemplate.self)
        PrimitiveRegistry.register(FRITemplate.self)
    }
}
